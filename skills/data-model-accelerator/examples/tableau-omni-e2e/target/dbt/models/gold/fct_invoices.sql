{{ config(materialized='table', schema='GOLD', alias='FCT_INVOICES') }}
WITH payment_totals AS (
  SELECT TENANT_ID, INVOICE_ID, SUM(PAID_CENTS) AS PAID_CENTS
  FROM {{ ref('billing_payments') }}
  GROUP BY TENANT_ID, INVOICE_ID
), invoice_values AS (
  SELECT i.TENANT_ID, i.INVOICE_ID, i.CUSTOMER_ID, i.INVOICE_DATE,
         CAST(DATE_TRUNC('MONTH', i.INVOICE_DATE) AS DATE) AS INVOICE_MONTH,
         i.STATUS, i.AMOUNT_CENTS,
         COALESCE(a.ADJUSTMENT_CENTS, 0) AS ADJUSTMENT_CENTS,
         i.AMOUNT_CENTS + COALESCE(a.ADJUSTMENT_CENTS, 0) AS NET_CENTS,
         COALESCE(p.PAID_CENTS, 0) AS PAID_CENTS,
         i.TENANT_ID || '|' || i.INVOICE_ID AS INVOICE_KEY,
         c.CUSTOMER_KEY, c.SEGMENT
  FROM {{ ref('billing_invoices') }} i
  LEFT JOIN {{ ref('billing_adjustments') }} a
    ON i.TENANT_ID = a.TENANT_ID AND i.INVOICE_ID = a.INVOICE_ID
  LEFT JOIN payment_totals p
    ON i.TENANT_ID = p.TENANT_ID AND i.INVOICE_ID = p.INVOICE_ID
  LEFT JOIN {{ ref('dim_customers') }} c
    ON i.TENANT_ID = c.TENANT_ID AND i.CUSTOMER_ID = c.CUSTOMER_ID
   AND i.INVOICE_DATE >= c.VALID_FROM
   AND (i.INVOICE_DATE < c.VALID_TO OR c.VALID_TO IS NULL)
)
SELECT TENANT_ID, INVOICE_ID, CUSTOMER_ID, INVOICE_DATE, INVOICE_MONTH,
       STATUS, AMOUNT_CENTS, ADJUSTMENT_CENTS, NET_CENTS, PAID_CENTS,
       NET_CENTS - PAID_CENTS AS OUTSTANDING_CENTS,
       INVOICE_KEY, CUSTOMER_KEY, SEGMENT
FROM invoice_values
