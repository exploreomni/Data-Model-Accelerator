-- Synthetic bootstrap DDL only; external source loading is a separate validated step.
-- RAW implements bronze responsibilities. No duplicate bronze copies are proposed.
CREATE DATABASE IF NOT EXISTS DMA_TABLEAU;
CREATE SCHEMA IF NOT EXISTS DMA_TABLEAU.RAW;
CREATE SCHEMA IF NOT EXISTS DMA_TABLEAU.SILVER;
CREATE SCHEMA IF NOT EXISTS DMA_TABLEAU.GOLD;
CREATE TABLE IF NOT EXISTS DMA_TABLEAU.RAW.INVOICE_CDC (
  TENANT_ID VARCHAR, INVOICE_ID VARCHAR, CUSTOMER_ID VARCHAR, INVOICE_DATE VARCHAR,
  AMOUNT_CENTS NUMBER(38,0), STATUS VARCHAR, IS_DELETED BOOLEAN, SEQUENCE NUMBER(38,0)
);
CREATE TABLE IF NOT EXISTS DMA_TABLEAU.RAW.PAYMENT_CDC (
  TENANT_ID VARCHAR, PAYMENT_ID VARCHAR, INVOICE_ID VARCHAR,
  PAID_CENTS NUMBER(38,0), IS_DELETED BOOLEAN, SEQUENCE NUMBER(38,0)
);
CREATE TABLE IF NOT EXISTS DMA_TABLEAU.RAW.CUSTOMER_HISTORY (
  TENANT_ID VARCHAR, CUSTOMER_ID VARCHAR, SEGMENT VARCHAR, VALID_FROM VARCHAR, VALID_TO VARCHAR
);
CREATE TABLE IF NOT EXISTS DMA_TABLEAU.RAW.ADJUSTMENTS (
  TENANT_ID VARCHAR, INVOICE_ID VARCHAR, ADJUSTMENT_CENTS NUMBER(38,0), REASON VARCHAR
);
