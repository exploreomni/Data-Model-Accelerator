SELECT i.TENANT_ID, i.INVOICE_ID
FROM {{ ref('billing_invoices') }} i
LEFT JOIN {{ ref('dim_customers') }} c
  ON i.TENANT_ID = c.TENANT_ID AND i.CUSTOMER_ID = c.CUSTOMER_ID
 AND i.INVOICE_DATE >= c.VALID_FROM AND (i.INVOICE_DATE < c.VALID_TO OR c.VALID_TO IS NULL)
GROUP BY i.TENANT_ID, i.INVOICE_ID
HAVING COUNT(c.CUSTOMER_KEY) <> 1
