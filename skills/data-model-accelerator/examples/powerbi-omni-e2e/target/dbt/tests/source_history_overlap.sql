WITH distinct_history AS (
  SELECT DISTINCT TENANT_ID, CUSTOMER_ID, SEGMENT,
         CAST(VALID_FROM AS DATE) AS VALID_FROM, CAST(VALID_TO AS DATE) AS VALID_TO
  FROM {{ source('raw', 'customer_history') }}
), numbered AS (
  SELECT *, ROW_NUMBER() OVER (
    PARTITION BY TENANT_ID, CUSTOMER_ID ORDER BY VALID_FROM, VALID_TO, SEGMENT
  ) AS HISTORY_ROW_NUMBER
  FROM distinct_history
)
SELECT a.TENANT_ID, a.CUSTOMER_ID, a.VALID_FROM, b.VALID_FROM AS OTHER_VALID_FROM
FROM numbered a JOIN numbered b
  ON a.TENANT_ID = b.TENANT_ID AND a.CUSTOMER_ID = b.CUSTOMER_ID
 AND a.HISTORY_ROW_NUMBER < b.HISTORY_ROW_NUMBER
 AND (a.VALID_TO IS NULL OR b.VALID_FROM < a.VALID_TO)
 AND (b.VALID_TO IS NULL OR a.VALID_FROM < b.VALID_TO)
