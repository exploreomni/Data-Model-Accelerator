WITH payments AS (
  SELECT TENANT_ID, INVOICE_ID, SUM(PAID_CENTS) AS EXPECTED_PAID_CENTS
  FROM {{ ref('billing_payments') }} GROUP BY TENANT_ID, INVOICE_ID
)
SELECT i.TENANT_ID, i.INVOICE_ID
FROM {{ ref('fct_invoices') }} i
LEFT JOIN payments p ON i.TENANT_ID = p.TENANT_ID AND i.INVOICE_ID = p.INVOICE_ID
WHERE i.PAID_CENTS <> COALESCE(p.EXPECTED_PAID_CENTS, 0)
