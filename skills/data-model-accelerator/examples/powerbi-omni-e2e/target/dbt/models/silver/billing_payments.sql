{{ config(materialized='table', schema='SILVER', alias='BILLING_PAYMENTS') }}
WITH versions AS (
  SELECT *, ROW_NUMBER() OVER (
    PARTITION BY TENANT_ID, PAYMENT_ID ORDER BY SEQUENCE DESC
  ) AS VERSION_RANK
  FROM {{ source('raw', 'payment_cdc') }}
)
SELECT TENANT_ID, PAYMENT_ID, INVOICE_ID,
       CAST(PAID_CENTS AS NUMBER(38,0)) AS PAID_CENTS,
       CAST(SEQUENCE AS NUMBER(38,0)) AS SOURCE_SEQUENCE
FROM versions
WHERE VERSION_RANK = 1 AND NOT IS_DELETED
