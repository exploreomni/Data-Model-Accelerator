SELECT i.TENANT_ID, i.INVOICE_ID
FROM {{ ref('fct_invoices') }} i
LEFT JOIN {{ ref('dim_customers') }} c ON i.CUSTOMER_KEY = c.CUSTOMER_KEY
WHERE i.NET_CENTS <> i.AMOUNT_CENTS + i.ADJUSTMENT_CENTS
   OR i.OUTSTANDING_CENTS <> i.NET_CENTS - i.PAID_CENTS
   OR c.CUSTOMER_KEY IS NULL OR i.TENANT_ID <> c.TENANT_ID OR i.CUSTOMER_ID <> c.CUSTOMER_ID
   OR i.SEGMENT <> c.SEGMENT OR i.INVOICE_DATE < c.VALID_FROM
   OR (c.VALID_TO IS NOT NULL AND i.INVOICE_DATE >= c.VALID_TO)
