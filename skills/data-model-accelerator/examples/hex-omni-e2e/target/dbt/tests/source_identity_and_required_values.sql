SELECT 'invalid_invoice_source' AS ISSUE
FROM {{ source('raw', 'invoice_cdc') }}
WHERE TENANT_ID IS NULL OR INVOICE_ID IS NULL OR CUSTOMER_ID IS NULL OR INVOICE_DATE IS NULL
   OR AMOUNT_CENTS IS NULL OR STATUS IS NULL OR IS_DELETED IS NULL OR SEQUENCE IS NULL OR SEQUENCE < 1
   OR TENANT_ID = '' OR INVOICE_ID = '' OR CUSTOMER_ID = ''
   OR TENANT_ID LIKE '%|%' OR INVOICE_ID LIKE '%|%' OR CUSTOMER_ID LIKE '%|%'
UNION ALL
SELECT 'invalid_payment_source' AS ISSUE
FROM {{ source('raw', 'payment_cdc') }}
WHERE TENANT_ID IS NULL OR PAYMENT_ID IS NULL OR INVOICE_ID IS NULL OR PAID_CENTS IS NULL
   OR IS_DELETED IS NULL OR SEQUENCE IS NULL OR SEQUENCE < 1
   OR TENANT_ID = '' OR PAYMENT_ID = '' OR INVOICE_ID = ''
   OR TENANT_ID LIKE '%|%' OR PAYMENT_ID LIKE '%|%' OR INVOICE_ID LIKE '%|%'
UNION ALL
SELECT 'invalid_history_source' AS ISSUE
FROM {{ source('raw', 'customer_history') }}
WHERE TENANT_ID IS NULL OR CUSTOMER_ID IS NULL OR SEGMENT IS NULL OR VALID_FROM IS NULL
   OR TENANT_ID = '' OR CUSTOMER_ID = '' OR SEGMENT = ''
   OR TENANT_ID LIKE '%|%' OR CUSTOMER_ID LIKE '%|%'
   OR (VALID_TO IS NOT NULL AND CAST(VALID_FROM AS DATE) >= CAST(VALID_TO AS DATE))
UNION ALL
SELECT 'invalid_adjustment_source' AS ISSUE
FROM {{ source('raw', 'adjustments') }}
WHERE TENANT_ID IS NULL OR INVOICE_ID IS NULL OR ADJUSTMENT_CENTS IS NULL OR REASON IS NULL
   OR TENANT_ID = '' OR INVOICE_ID = ''
   OR TENANT_ID LIKE '%|%' OR INVOICE_ID LIKE '%|%'
